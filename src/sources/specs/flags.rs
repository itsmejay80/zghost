#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Value {
    None,
    Text,
    File,
    Directory,
    Choices(&'static [&'static str]),
}
pub(crate) struct Flag {
    pub scope: &'static str,
    pub names: &'static str,
    pub value: Value,
}
impl Flag {
    pub fn repeatable(&self) -> bool {
        self.names.split_whitespace().any(|n| {
            matches!(
                n,
                "--env"
                    | "--publish"
                    | "--volume"
                    | "--header"
                    | "--values"
                    | "--set"
                    | "--var"
                    | "-var"
                    | "--glob"
                    | "--features"
            )
        }) || (self.scope == "git" && self.names == "-c")
    }
}
macro_rules! flag {
    ($scope:literal, $names:literal, $value:expr) => {
        Flag {
            scope: $scope,
            names: $names,
            value: $value,
        }
    };
}
